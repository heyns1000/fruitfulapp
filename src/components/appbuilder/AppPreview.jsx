import React, { useState } from 'react';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import { Download, FileJson, FileCode, Copy, Check, Palette, Database, Zap } from 'lucide-react';
import { toast } from 'sonner';

export default function AppPreview({ appData, selectedBrands }) {
  const [copied, setCopied] = useState(false);

  const copyToClipboard = (data, label) => {
    navigator.clipboard.writeText(typeof data === 'object' ? JSON.stringify(data, null, 2) : data);
    toast.success(`${label} copied to clipboard!`);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const downloadJSON = () => {
    const dataStr = JSON.stringify(appData, null, 2);
    const blob = new Blob([dataStr], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${appData.appName.replace(/\s+/g, '_')}_app_structure.json`;
    link.click();
    URL.revokeObjectURL(url);
    toast.success('App structure downloaded!');
  };

  const downloadReadme = () => {
    const readme = `# ${appData.appName}

${appData.tagline || appData.description}

## Overview
This app was generated using the FAA.ZONE App Builder with the following brands:
${selectedBrands.map(b => `- ${b.name}™ (${b.sector})`).join('\n')}

## Tech Stack
### Frontend
${appData.techStack?.frontend?.map(t => `- ${t}`).join('\n') || 'N/A'}

### Backend
${appData.techStack?.backend?.map(t => `- ${t}`).join('\n') || 'N/A'}

### Database
- ${appData.techStack?.database || 'N/A'}

## Pages
${appData.pages?.map(p => `
### ${p.name} (${p.route})
${p.description}

**Sections:**
${p.sections?.map(s => `- ${s}`).join('\n') || 'None'}
`).join('\n') || 'No pages defined'}

## Key Features
${appData.features?.map(f => `
### ${f.name}
${f.description}
**Related Brands:** ${f.relatedBrands?.join(', ') || 'None'}
`).join('\n') || 'No features defined'}

## Cross-Pollination Strategy
${appData.crossPollination?.map(cp => `
- **${cp.brand1}** + **${cp.brand2}**
  - Connection: ${cp.connectionType}
  - Feature: ${cp.feature}
`).join('\n') || 'No cross-pollination defined'}

## Database Schema
${appData.databaseSchema?.map(table => `
### ${table.tableName}
Fields:
${table.fields?.map(f => `- ${f}`).join('\n') || 'None'}
`).join('\n') || 'No schema defined'}

## Color Scheme
- Primary: ${appData.colorScheme?.primary || 'N/A'}
- Secondary: ${appData.colorScheme?.secondary || 'N/A'}
- Accent: ${appData.colorScheme?.accent || 'N/A'}

---
Generated by FAA.ZONE App Builder on ${new Date(appData.generatedAt).toLocaleDateString()}
`;

    const blob = new Blob([readme], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${appData.appName.replace(/\s+/g, '_')}_README.md`;
    link.click();
    URL.revokeObjectURL(url);
    toast.success('README.md downloaded!');
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <Card className="border-2 border-green-200 bg-gradient-to-br from-green-50 to-emerald-50">
        <CardHeader>
          <div className="flex justify-between items-start">
            <div>
              <CardTitle className="text-3xl text-green-900">{appData.appName}</CardTitle>
              <CardDescription className="text-lg mt-2">
                {appData.tagline || appData.description}
              </CardDescription>
            </div>
            <div className="flex gap-2">
              <Button
                onClick={downloadJSON}
                variant="outline"
                className="border-green-300 text-green-700 hover:bg-green-50"
              >
                <FileJson className="w-4 h-4 mr-2" />
                Export JSON
              </Button>
              <Button
                onClick={downloadReadme}
                variant="outline"
                className="border-blue-300 text-blue-700 hover:bg-blue-50"
              >
                <FileCode className="w-4 h-4 mr-2" />
                Export README
              </Button>
            </div>
          </div>
        </CardHeader>
      </Card>

      <Tabs defaultValue="overview" className="space-y-6">
        <TabsList className="bg-white/90 p-2 rounded-xl shadow-lg border-2 border-gray-200 flex-wrap justify-start">
          <TabsTrigger value="overview">📊 Overview</TabsTrigger>
          <TabsTrigger value="pages">📄 Pages</TabsTrigger>
          <TabsTrigger value="features">⚡ Features</TabsTrigger>
          <TabsTrigger value="crosspoll">🔗 Cross-Pollination</TabsTrigger>
          <TabsTrigger value="tech">💻 Tech Stack</TabsTrigger>
          <TabsTrigger value="database">🗄️ Database</TabsTrigger>
        </TabsList>

        <TabsContent value="overview">
          <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
            {/* Color Scheme */}
            <Card>
              <CardHeader>
                <CardTitle className="flex items-center gap-2">
                  <Palette className="w-5 h-5" />
                  Color Scheme
                </CardTitle>
              </CardHeader>
              <CardContent className="space-y-3">
                <div className="flex items-center gap-3">
                  <div
                    className="w-12 h-12 rounded-lg shadow-md border-2 border-gray-200"
                    style={{ backgroundColor: appData.colorScheme?.primary }}
                  />
                  <div>
                    <div className="font-semibold">Primary</div>
                    <div className="text-sm text-gray-600">{appData.colorScheme?.primary}</div>
                  </div>
                </div>
                <div className="flex items-center gap-3">
                  <div
                    className="w-12 h-12 rounded-lg shadow-md border-2 border-gray-200"
                    style={{ backgroundColor: appData.colorScheme?.secondary }}
                  />
                  <div>
                    <div className="font-semibold">Secondary</div>
                    <div className="text-sm text-gray-600">{appData.colorScheme?.secondary}</div>
                  </div>
                </div>
                <div className="flex items-center gap-3">
                  <div
                    className="w-12 h-12 rounded-lg shadow-md border-2 border-gray-200"
                    style={{ backgroundColor: appData.colorScheme?.accent }}
                  />
                  <div>
                    <div className="font-semibold">Accent</div>
                    <div className="text-sm text-gray-600">{appData.colorScheme?.accent}</div>
                  </div>
                </div>
              </CardContent>
            </Card>

            {/* Brands */}
            <Card>
              <CardHeader>
                <CardTitle>Integrated Brands</CardTitle>
              </CardHeader>
              <CardContent>
                <div className="space-y-2">
                  {selectedBrands.map(brand => (
                    <div key={brand.id} className="p-3 bg-gray-50 rounded-lg border">
                      <div className="font-semibold text-gray-900">{brand.name}™</div>
                      <div className="text-xs text-gray-600 mt-1">
                        {brand.subnodes?.length || 0} subnodes · {brand.sector}
                      </div>
                    </div>
                  ))}
                </div>
              </CardContent>
            </Card>
          </div>
        </TabsContent>

        <TabsContent value="pages">
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            {appData.pages?.map((page, idx) => (
              <Card key={idx}>
                <CardHeader>
                  <CardTitle className="text-lg">{page.name}</CardTitle>
                  <CardDescription>
                    <Badge variant="outline">{page.route}</Badge>
                  </CardDescription>
                </CardHeader>
                <CardContent>
                  <p className="text-sm text-gray-700 mb-3">{page.description}</p>
                  {page.sections?.length > 0 && (
                    <div>
                      <div className="text-sm font-semibold mb-2">Sections:</div>
                      <div className="flex flex-wrap gap-2">
                        {page.sections.map((section, i) => (
                          <Badge key={i} variant="secondary" className="text-xs">
                            {section}
                          </Badge>
                        ))}
                      </div>
                    </div>
                  )}
                </CardContent>
              </Card>
            ))}
          </div>
        </TabsContent>

        <TabsContent value="features">
          <div className="space-y-4">
            {appData.features?.map((feature, idx) => (
              <Card key={idx}>
                <CardHeader>
                  <CardTitle className="flex items-center gap-2">
                    <Zap className="w-5 h-5 text-yellow-600" />
                    {feature.name}
                  </CardTitle>
                </CardHeader>
                <CardContent>
                  <p className="text-gray-700 mb-3">{feature.description}</p>
                  {feature.relatedBrands?.length > 0 && (
                    <div className="flex items-center gap-2">
                      <span className="text-sm font-semibold">Related Brands:</span>
                      <div className="flex flex-wrap gap-2">
                        {feature.relatedBrands.map((brand, i) => (
                          <Badge key={i} className="bg-indigo-100 text-indigo-800">
                            {brand}
                          </Badge>
                        ))}
                      </div>
                    </div>
                  )}
                </CardContent>
              </Card>
            ))}
          </div>
        </TabsContent>

        <TabsContent value="crosspoll">
          <div className="space-y-4">
            {appData.crossPollination?.map((cp, idx) => (
              <Card key={idx} className="border-2 border-purple-200 bg-purple-50">
                <CardContent className="pt-6">
                  <div className="flex items-center gap-4 mb-3">
                    <Badge className="bg-purple-600 text-white">{cp.brand1}</Badge>
                    <span className="text-2xl">🤝</span>
                    <Badge className="bg-purple-600 text-white">{cp.brand2}</Badge>
                  </div>
                  <div className="space-y-2 text-sm">
                    <div>
                      <span className="font-semibold">Connection Type:</span> {cp.connectionType}
                    </div>
                    <div>
                      <span className="font-semibold">Feature:</span> {cp.feature}
                    </div>
                  </div>
                </CardContent>
              </Card>
            ))}
          </div>
        </TabsContent>

        <TabsContent value="tech">
          <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
            <Card>
              <CardHeader>
                <CardTitle className="text-lg">Frontend</CardTitle>
              </CardHeader>
              <CardContent>
                <ul className="space-y-2">
                  {appData.techStack?.frontend?.map((tech, i) => (
                    <li key={i} className="flex items-center gap-2">
                      <div className="w-2 h-2 bg-blue-500 rounded-full" />
                      <span className="text-sm">{tech}</span>
                    </li>
                  ))}
                </ul>
              </CardContent>
            </Card>

            <Card>
              <CardHeader>
                <CardTitle className="text-lg">Backend</CardTitle>
              </CardHeader>
              <CardContent>
                <ul className="space-y-2">
                  {appData.techStack?.backend?.map((tech, i) => (
                    <li key={i} className="flex items-center gap-2">
                      <div className="w-2 h-2 bg-green-500 rounded-full" />
                      <span className="text-sm">{tech}</span>
                    </li>
                  ))}
                </ul>
              </CardContent>
            </Card>

            <Card>
              <CardHeader>
                <CardTitle className="text-lg">Database</CardTitle>
              </CardHeader>
              <CardContent>
                <div className="flex items-center gap-2">
                  <Database className="w-5 h-5 text-purple-600" />
                  <span className="font-semibold">{appData.techStack?.database}</span>
                </div>
              </CardContent>
            </Card>
          </div>
        </TabsContent>

        <TabsContent value="database">
          <div className="space-y-4">
            {appData.databaseSchema?.map((table, idx) => (
              <Card key={idx}>
                <CardHeader>
                  <CardTitle className="flex items-center gap-2">
                    <Database className="w-5 h-5 text-indigo-600" />
                    {table.tableName}
                  </CardTitle>
                </CardHeader>
                <CardContent>
                  <div className="grid grid-cols-2 md:grid-cols-3 gap-2">
                    {table.fields?.map((field, i) => (
                      <div key={i} className="px-3 py-2 bg-gray-50 rounded border text-sm">
                        {field}
                      </div>
                    ))}
                  </div>
                </CardContent>
              </Card>
            ))}
          </div>
        </TabsContent>
      </Tabs>
    </div>
  );
}