import React, { useState } from 'react';
import { Button } from '@/components/ui/button';
import { Badge } from '@/components/ui/badge';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import {
  Download, FileJson, FileCode, Copy, Check, Palette, Database,
  Zap, Code2, Eye, Shield, Globe, Star, RotateCcw, GitBranch, Layers
} from 'lucide-react';
import { toast } from 'sonner';

export default function HotStackPreview({ appData, selectedBrands, onRebuild }) {
  const [copied, setCopied] = useState(false);

  const copy = (data, label) => {
    navigator.clipboard.writeText(typeof data === 'object' ? JSON.stringify(data, null, 2) : data);
    toast.success(`${label} copied!`);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const downloadJSON = () => {
    const blob = new Blob([JSON.stringify(appData, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url; a.download = `${appData.appName?.replace(/\s+/g, '_')}_hotstack.json`;
    a.click(); URL.revokeObjectURL(url);
    toast.success('JSON downloaded!');
  };

  const downloadReadme = () => {
    const md = `# ${appData.appName}
> ${appData.tagline || ''}

Generated by HotStack™ · FAA.ZONE App Builder · ${new Date(appData.generatedAt).toLocaleDateString()}

## Vibe Prompt
> "${appData.vibePrompt || ''}"

## Ecosystem Brands Used
${selectedBrands.map(b => `- **${b.name}™** (${b.sector}) · ${b.subnodes?.length || 0} subnodes`).join('\n')}

## Pages
${appData.pages?.map(p => `### ${p.name} \`${p.route}\`\n${p.description}\n${p.sections?.map(s => `- ${s}`).join('\n') || ''}`).join('\n\n') || 'None'}

## Key Features
${appData.features?.map(f => `### ${f.name}\n${f.description}\n**Brands:** ${f.relatedBrands?.join(', ')}`).join('\n\n') || 'None'}

## Cross-Pollination
${appData.crossPollination?.map(c => `- **${c.brand1}** + **${c.brand2}** — ${c.connectionType} · Score: ${c.synergyScore || 'N/A'}`).join('\n') || 'None'}

## Tech Stack
**Frontend:** ${appData.techStack?.frontend?.join(', ') || 'N/A'}
**Backend:** ${appData.techStack?.backend?.join(', ') || 'N/A'}
**Database:** ${appData.techStack?.database || 'N/A'}

## Colors
- Primary: ${appData.colorScheme?.primary || 'N/A'}
- Secondary: ${appData.colorScheme?.secondary || 'N/A'}
- Accent: ${appData.colorScheme?.accent || 'N/A'}
`;
    const blob = new Blob([md], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a'); a.href = url;
    a.download = `${appData.appName?.replace(/\s+/g, '_')}_README.md`;
    a.click(); URL.revokeObjectURL(url);
    toast.success('README downloaded!');
  };

  const downloadReact = () => {
    const code = `// ${appData.appName} — React Starter
// Generated by HotStack™ · ${new Date(appData.generatedAt).toLocaleDateString()}
// Vibe: "${appData.vibePrompt || ''}"

import React from 'react';
import { BrowserRouter, Routes, Route } from 'react-router-dom';

// Color Theme
export const THEME = {
  primary: '${appData.colorScheme?.primary || '#f97316'}',
  secondary: '${appData.colorScheme?.secondary || '#1c1917'}',
  accent: '${appData.colorScheme?.accent || '#f59e0b'}',
};

// User Roles
export const ROLES = ${JSON.stringify(appData.userRoles || [], null, 2)};

// Pages to build:
${appData.pages?.map(p => `// ${p.name.replace(/\s+/g, '')}Page → ${p.route}\n//   ${p.description}`).join('\n') || ''}

// Cross-pollination pairs from real ecosystem:
${appData.crossPollination?.slice(0, 5).map(c => `// ${c.brand1} + ${c.brand2}: ${c.feature}`).join('\n') || ''}

function App() {
  return (
    <BrowserRouter>
      <Routes>
        ${appData.pages?.map(p => `<Route path="${p.route}" element={<div>{/* ${p.name} */}</div>} />`).join('\n        ') || ''}
      </Routes>
    </BrowserRouter>
  );
}

export default App;
`;
    const blob = new Blob([code], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a'); a.href = url;
    a.download = `${appData.appName?.replace(/\s+/g, '_')}_react_starter.jsx`;
    a.click(); URL.revokeObjectURL(url);
    toast.success('React starter downloaded!');
  };

  return (
    <div className="max-w-6xl mx-auto pt-4 space-y-6">
      {/* Header */}
      <div className="bg-gradient-to-r from-stone-900 to-stone-800 border border-stone-700 rounded-2xl p-6">
        <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
          <div>
            <div className="flex items-center gap-2 mb-2">
              <div className="w-2 h-2 bg-green-400 rounded-full animate-pulse" />
              <span className="text-green-400 text-xs font-bold tracking-widest uppercase">HotStack™ Build Complete</span>
            </div>
            <h1 className="text-3xl font-black text-white">{appData.appName}</h1>
            <p className="text-stone-400 mt-1">{appData.tagline}</p>
            <div className="flex flex-wrap gap-2 mt-3">
              {selectedBrands.slice(0, 5).map(b => (
                <Badge key={b.id} className="bg-stone-700 border border-stone-600 text-stone-300 text-xs">{b.name}™</Badge>
              ))}
              {selectedBrands.length > 5 && (
                <Badge className="bg-stone-700 border border-stone-600 text-stone-400 text-xs">+{selectedBrands.length - 5} more</Badge>
              )}
            </div>
          </div>
          <div className="flex flex-wrap gap-2 shrink-0">
            <Button onClick={onRebuild} variant="outline" className="border-stone-600 text-stone-300 hover:bg-stone-700 gap-2 text-sm">
              <RotateCcw className="w-3.5 h-3.5" /> Rebuild
            </Button>
            <Button onClick={downloadJSON} variant="outline" className="border-orange-700 text-orange-400 hover:bg-orange-950/30 gap-2 text-sm">
              <FileJson className="w-3.5 h-3.5" /> JSON
            </Button>
            <Button onClick={downloadReadme} variant="outline" className="border-teal-700 text-teal-400 hover:bg-teal-950/30 gap-2 text-sm">
              <FileCode className="w-3.5 h-3.5" /> README
            </Button>
            <Button onClick={downloadReact} className="bg-orange-500 hover:bg-orange-400 text-black font-black gap-2 text-sm">
              <Download className="w-3.5 h-3.5" /> React Code
            </Button>
          </div>
        </div>
      </div>

      <Tabs defaultValue="overview" className="space-y-5">
        <TabsList className="bg-stone-900 border border-stone-800 p-1.5 rounded-xl flex-wrap gap-1 h-auto">
          {[
            ['overview', '📊 Overview'],
            ['pages', '📄 Pages'],
            ['features', '⚡ Features'],
            ['crosspoll', '🔗 Cross-Poll'],
            ['database', '🗄️ Schema'],
            ['roles', '🛡️ Roles'],
            ['visualise', '👁️ Visualise'],
          ].map(([val, label]) => (
            <TabsTrigger key={val} value={val} className="data-[state=active]:bg-orange-500 data-[state=active]:text-black text-stone-400 text-xs font-bold rounded-lg px-3 py-1.5 transition-all">
              {label}
            </TabsTrigger>
          ))}
        </TabsList>

        {/* Overview */}
        <TabsContent value="overview">
          <div className="grid grid-cols-1 md:grid-cols-3 gap-5">
            <div className="md:col-span-2 bg-stone-900 border border-stone-800 rounded-xl p-5 space-y-4">
              <h3 className="text-white font-black flex items-center gap-2"><Palette className="w-5 h-5 text-orange-500" /> Colour Scheme</h3>
              <div className="flex gap-4">
                {[['Primary', appData.colorScheme?.primary], ['Secondary', appData.colorScheme?.secondary], ['Accent', appData.colorScheme?.accent]].map(([label, hex]) => (
                  <div key={label} className="flex items-center gap-2">
                    <div className="w-10 h-10 rounded-lg border border-stone-700 shadow-md" style={{ backgroundColor: hex || '#888' }} />
                    <div>
                      <p className="text-stone-300 text-xs font-bold">{label}</p>
                      <p className="text-stone-500 text-xs font-mono">{hex || '—'}</p>
                    </div>
                  </div>
                ))}
              </div>
              <div className="pt-3 border-t border-stone-800">
                <h4 className="text-stone-400 text-xs font-bold uppercase tracking-wider mb-2">Tech Stack</h4>
                <div className="flex flex-wrap gap-2">
                  {[...(appData.techStack?.frontend || []), ...(appData.techStack?.backend || []), appData.techStack?.database].filter(Boolean).map((t, i) => (
                    <Badge key={i} className="bg-stone-800 border border-stone-700 text-stone-300 text-xs">{t}</Badge>
                  ))}
                </div>
              </div>
            </div>
            <div className="bg-stone-900 border border-stone-800 rounded-xl p-5 space-y-3">
              <h3 className="text-white font-black flex items-center gap-2"><Layers className="w-5 h-5 text-teal-400" /> Ecosystem Data</h3>
              <div className="space-y-2">
                {[
                  ['Pages generated', appData.pages?.length || 0],
                  ['Features', appData.features?.length || 0],
                  ['Cross-poll pairs', appData.crossPollination?.length || 0],
                  ['DB tables', appData.databaseSchema?.length || 0],
                  ['Real brands', selectedBrands.length],
                  ['Total subnodes', selectedBrands.reduce((s, b) => s + (b.subnodes?.length || 0), 0)],
                ].map(([label, val]) => (
                  <div key={label} className="flex justify-between items-center">
                    <span className="text-stone-500 text-xs">{label}</span>
                    <span className="text-orange-400 font-black text-sm">{val}</span>
                  </div>
                ))}
              </div>
            </div>
          </div>
        </TabsContent>

        {/* Pages */}
        <TabsContent value="pages">
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-4">
            {appData.pages?.map((page, idx) => (
              <div key={idx} className="bg-stone-900 border border-stone-800 rounded-xl p-5 hover:border-orange-500/30 transition-all">
                <div className="flex items-start justify-between mb-2">
                  <h3 className="text-white font-black text-sm">{page.name}</h3>
                  <Badge className="bg-stone-800 border border-stone-700 text-stone-500 text-[10px] font-mono">{page.route}</Badge>
                </div>
                <p className="text-stone-400 text-xs mb-3">{page.description}</p>
                <div className="flex flex-wrap gap-1">
                  {page.sections?.map((s, i) => (
                    <span key={i} className="text-[10px] bg-stone-800 text-stone-400 px-2 py-0.5 rounded-full">{s}</span>
                  ))}
                </div>
              </div>
            ))}
          </div>
        </TabsContent>

        {/* Features */}
        <TabsContent value="features">
          <div className="space-y-3">
            {appData.features?.map((f, idx) => (
              <div key={idx} className="bg-stone-900 border border-stone-800 rounded-xl p-5 flex flex-col sm:flex-row sm:items-start gap-4">
                <div className="w-8 h-8 bg-orange-500/10 border border-orange-500/30 rounded-lg flex items-center justify-center shrink-0">
                  <Zap className="w-4 h-4 text-orange-400" />
                </div>
                <div className="flex-1">
                  <h3 className="text-white font-black text-sm">{f.name}</h3>
                  <p className="text-stone-400 text-xs mt-1">{f.description}</p>
                  {f.relatedBrands?.length > 0 && (
                    <div className="flex flex-wrap gap-1.5 mt-2">
                      {f.relatedBrands.map((b, i) => (
                        <Badge key={i} className="bg-stone-800 border border-stone-700 text-stone-400 text-[10px]">{b}</Badge>
                      ))}
                    </div>
                  )}
                </div>
              </div>
            ))}
          </div>
        </TabsContent>

        {/* Cross-pollination */}
        <TabsContent value="crosspoll">
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            {appData.crossPollination?.map((cp, idx) => (
              <div key={idx} className="bg-stone-900 border border-purple-900/50 rounded-xl p-5">
                <div className="flex items-center gap-2 mb-3">
                  <Badge className="bg-purple-900/40 border border-purple-700 text-purple-300 text-xs font-black">{cp.brand1}</Badge>
                  <span className="text-stone-500">×</span>
                  <Badge className="bg-purple-900/40 border border-purple-700 text-purple-300 text-xs font-black">{cp.brand2}</Badge>
                  {cp.synergyScore && (
                    <span className="ml-auto text-orange-400 font-black text-sm">{cp.synergyScore}%</span>
                  )}
                </div>
                <p className="text-stone-300 text-xs font-bold">{cp.connectionType}</p>
                <p className="text-stone-500 text-xs mt-1">{cp.feature}</p>
              </div>
            ))}
          </div>
        </TabsContent>

        {/* Database */}
        <TabsContent value="database">
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            {appData.databaseSchema?.map((table, idx) => (
              <div key={idx} className="bg-stone-900 border border-stone-800 rounded-xl overflow-hidden">
                <div className="flex items-center gap-2 px-4 py-3 bg-stone-800/60 border-b border-stone-700">
                  <Database className="w-4 h-4 text-teal-400" />
                  <span className="text-white font-black text-sm font-mono">{table.tableName}</span>
                </div>
                <div className="p-4 space-y-1.5">
                  {table.fields?.map((field, i) => (
                    <div key={i} className="text-xs font-mono text-stone-400 flex items-center gap-2">
                      <span className="text-stone-700">—</span> {field}
                    </div>
                  ))}
                </div>
              </div>
            ))}
          </div>
        </TabsContent>

        {/* Roles */}
        <TabsContent value="roles">
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            {appData.rolePermissions?.roles?.map((role, idx) => (
              <div key={idx} className="bg-stone-900 border border-stone-800 rounded-xl p-5">
                <div className="flex items-center justify-between mb-2">
                  <h3 className="text-white font-black flex items-center gap-2">
                    <Shield className="w-4 h-4 text-indigo-400" /> {role.name}
                  </h3>
                  <Badge className="bg-indigo-900/40 border border-indigo-700 text-indigo-300 text-xs">{role.permissions?.length || 0} perms</Badge>
                </div>
                <p className="text-stone-500 text-xs mb-3">{role.description}</p>
                <div className="flex flex-wrap gap-1.5">
                  {role.permissions?.map((p, i) => (
                    <span key={i} className="text-[10px] bg-stone-800 text-stone-400 px-2 py-0.5 rounded-full">✓ {p}</span>
                  ))}
                </div>
              </div>
            ))}
          </div>
        </TabsContent>

        {/* Visualise */}
        <TabsContent value="visualise">
          <div
            className="rounded-2xl p-8 min-h-[500px] border-2"
            style={{
              borderColor: appData.colorScheme?.primary || '#f97316',
              background: `linear-gradient(135deg, ${appData.colorScheme?.primary || '#f97316'}08, ${appData.colorScheme?.secondary || '#1c1917'}30)`,
            }}
          >
            {/* Simulated app nav */}
            <div className="rounded-xl p-5 mb-6 text-white shadow-2xl" style={{ backgroundColor: appData.colorScheme?.primary || '#f97316' }}>
              <div className="flex items-center justify-between">
                <h2 className="text-2xl font-black">{appData.appName}</h2>
                <div className="flex gap-2 flex-wrap">
                  {appData.pages?.slice(0, 5).map((p, i) => (
                    <span key={i} className="px-3 py-1 bg-white/20 rounded-lg text-xs font-bold hover:bg-white/30 cursor-pointer transition-all">{p.name}</span>
                  ))}
                </div>
              </div>
              <p className="text-white/80 text-sm mt-2">{appData.tagline}</p>
            </div>
            {/* Feature cards */}
            <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 gap-4">
              {appData.features?.slice(0, 6).map((f, idx) => (
                <div key={idx} className="bg-white/90 rounded-xl p-5 shadow-md border-t-4" style={{ borderColor: appData.colorScheme?.accent || '#f59e0b' }}>
                  <h4 className="font-black text-gray-900 text-sm">{f.name}</h4>
                  <p className="text-gray-500 text-xs mt-1">{f.description?.slice(0, 80)}…</p>
                </div>
              ))}
            </div>
          </div>
        </TabsContent>
      </Tabs>
    </div>
  );
}